const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

// Fixed-crop thumbnails for homepage cards — much smaller than the
// full (max-1200px-wide) article image, since no homepage card ever
// renders anywhere near that size.
const THUMB_SIZE = { width: 230, height: 120 };
const LARGE_SIZE = { width: 460, height: 335 };
const ARTICLE_SIZE = { width: 630, height: 420 };
// Mobile-viewport variants for the homepage hero/thumbnail grid — same
// crop intent as LARGE_SIZE/THUMB_SIZE but sized for phone screens
// (measured on iPhone XR) instead of serving the desktop crop at a
// smaller display size.
const MOBILE_HERO_SIZE = { width: 520, height: 350 };
const MOBILE_THUMB_SIZE = { width: 515, height: 200 };
const DEFAULT_IMAGE = '/uploads/defaults/at-news.png';

const DIR_BY_PREFIX = [
  { prefix: '/uploads/articles/', dir: process.env.UPLOADS_ARTICLES_DIR },
  { prefix: '/uploads/defaults/', dir: process.env.UPLOADS_DEFAULTS_DIR },
];

function resolveDir(url) {
  const match = DIR_BY_PREFIX.find((d) => url.startsWith(d.prefix));
  return match ? match.dir : null;
}

function withSuffix(url, suffix, ext) {
  return url.replace(/\.[a-zA-Z0-9]+$/, `${suffix}${ext}`);
}

// Most articles don't have a generated variant yet (only the ~20 that
// currently appear on the homepage do, generated by
// scripts/backfill-homepage-thumbs.js) — fall back to the full-size
// image whenever the variant file isn't there rather than link to a
// 404. New uploads get variants immediately via compressArticleImages,
// so this fallback only bites on old articles.
//
// New uploads generate .webp variants; articles from before the WebP
// switch have .jpg variants. Prefer .webp, fall back to .jpg, then to
// the original — so both old and new articles resolve correctly without
// storing the variant extension in the DB.
function variantUrl(featuredImage, suffix) {
  const url = featuredImage || DEFAULT_IMAGE;
  const dir = resolveDir(url);
  if (dir) {
    for (const ext of ['.webp', '.jpg']) {
      const candidateUrl = withSuffix(url, suffix, ext);
      if (fs.existsSync(path.join(dir, path.basename(candidateUrl)))) {
        return candidateUrl;
      }
    }
  }
  return url;
}

function thumbUrl(featuredImage) {
  return variantUrl(featuredImage, '-thumb');
}

function largeUrl(featuredImage) {
  return variantUrl(featuredImage, '-large');
}

function mobileHeroUrl(featuredImage) {
  return variantUrl(featuredImage, '-mobile-hero');
}

function mobileThumbUrl(featuredImage) {
  return variantUrl(featuredImage, '-mobile-thumb');
}

// Article page's own featured-image display — never the original
// full-size upload (admin editor preview is the one place that still
// uses the original directly, by design).
function articleImageUrl(featuredImage) {
  return variantUrl(featuredImage, '-article');
}

// Variants are WebP now (smaller than JPEG at equal quality). An animated
// GIF source is flattened to its first frame here — fine for these fixed-size
// crops (homepage cards/thumbnails never animate anyway); the full-size GIF
// original is left untouched by compressImageFile so its animation survives.
async function generateSizedVariants(sourcePath, outputDir, baseNameNoExt) {
  const thumbPath = path.join(outputDir, `${baseNameNoExt}-thumb.webp`);
  const largePath = path.join(outputDir, `${baseNameNoExt}-large.webp`);
  const articlePath = path.join(outputDir, `${baseNameNoExt}-article.webp`);
  const mobileHeroPath = path.join(outputDir, `${baseNameNoExt}-mobile-hero.webp`);
  const mobileThumbPath = path.join(outputDir, `${baseNameNoExt}-mobile-thumb.webp`);

  await sharp(sourcePath).resize({ ...THUMB_SIZE, fit: 'cover' }).webp({ quality: 75 }).toFile(thumbPath);
  await sharp(sourcePath).resize({ ...LARGE_SIZE, fit: 'cover' }).webp({ quality: 80 }).toFile(largePath);
  await sharp(sourcePath).resize({ ...ARTICLE_SIZE, fit: 'cover' }).webp({ quality: 80 }).toFile(articlePath);
  await sharp(sourcePath).resize({ ...MOBILE_HERO_SIZE, fit: 'cover', position: 'centre' }).webp({ quality: 80 }).toFile(mobileHeroPath);
  await sharp(sourcePath).resize({ ...MOBILE_THUMB_SIZE, fit: 'cover', position: 'centre' }).webp({ quality: 75 }).toFile(mobileThumbPath);

  return { thumbPath, largePath, articlePath, mobileHeroPath, mobileThumbPath };
}

module.exports = {
  thumbUrl,
  largeUrl,
  mobileHeroUrl,
  mobileThumbUrl,
  articleImageUrl,
  generateSizedVariants,
  DEFAULT_IMAGE,
  THUMB_SIZE,
  LARGE_SIZE,
  ARTICLE_SIZE,
  MOBILE_HERO_SIZE,
  MOBILE_THUMB_SIZE,
};
